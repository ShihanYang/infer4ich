
import pandas as pd
import numpy as np
from statsmodels.stats.inter_rater import fleiss_kappa

def calculate_fleiss_kappa_from_df(df, rating_column):
    # Fleiss' Kappa‌ 是一种用于评估‌多个评价者‌（通常≥3）对同一组对象进行分类时‌一致性程度‌的统计量
    # Fleiss' Kappa 的核心思想是比较‌实际观察到的一致性比例‌$p_o$与随机一致性比例$p_e$直接的差异 $k=(p_o - p_e)/(1-p_e)$
    
    # 构建评级矩阵 (n_items x n_categories), 实际是频数矩阵
    items = df['item_id'].unique()
    n_items = len(items)
    n_categories = 5  # 1 to 5
    
    # 初始化计数矩阵
    rating_matrix = np.zeros((n_items, n_categories))
    # 频数统计
    for idx, item in enumerate(items):
        item_ratings = df[df['item_id'] == item][rating_column]
        for rate in item_ratings:
            if 1 <= rate <= 5:
                rating_matrix[idx, int(rate)-1] += 10   # Augmentation 
                
    # 检查是否所有项目都有相同数量的评分者
    row_sums = rating_matrix.sum(axis=1)
    if not np.all(row_sums == row_sums):
        raise ValueError("所有项目必须由相同数量的评分者评估才能使用标准 Fleiss' Kappa")
        
    kappa = fleiss_kappa(rating_matrix, method='fleiss')
    return kappa

def generate_reliability_report(df):
    print("\n--- Appraisal Report on the Reliability of Wordsets Generated by LLM ---\n")
    
    # 1. 基本统计
    total_items = df['item_id'].nunique()
    total_experts = df['exp_id'].nunique()
    total_facets = df['assessment_dim'].nunique()
    columns = list(df.columns)
    features = [col for col in columns if 'F_score' in col]
    total_features = len(features)  
    print(f"All items: {total_items}")
    print(f"All features of each item: {total_features}")
    print(f"All experts: {total_experts}")    
    print(f"All facets: {total_facets}")
    
    for feature in features:
        print(f"\n--- For {feature} ---")
        
        # 2. 计算相关性维度的 Kappa
        try:
            kappa_rel = calculate_fleiss_kappa_from_df(df[df['assessment_dim']=='relevance'], feature)
            print(f"\n  [Relevance Facet] Fleiss' Kappa: {kappa_rel:.4f}")
            interpret_kappa(kappa_rel, "Relevance")
            ## 在大语言模型（LLM）的评估体系中，相关性维度是衡量模型输出质量的核心指标之一。
            ## 它聚焦于模型生成内容与用户输入需求的匹配程度，直接决定了模型能否有效解决用户问题、满足用户期望。
        except Exception as e:
            print(f"\n[相关性维度] 计算失败: {e}")

        # 3. 计算准确性维度的 Kappa
        try:
            kappa_acc = calculate_fleiss_kappa_from_df(df[df['assessment_dim']=='accuracy'], feature)
            print(f"  [Accuracy Facet] Fleiss' Kappa: {kappa_acc:.4f}")
            interpret_kappa(kappa_acc, "Accuracy")
            ## 在大语言模型（LLM）的评估体系中，准确性是衡量模型性能的核心指标之一，它指的是模型输出结果与真实情况、客观事实或预期标准的契合程度。
            ## 对于LLM而言，准确性直接决定了其在实际应用中的可靠性与实用性，是模型赢得用户信任的基础。
        except Exception as e:
            print(f"[准确性维度] 计算失败: {e}")

        # 4. 平均得分统计
        mean_scores = df.groupby('assessment_dim')[feature].mean()
        std_scores = df.groupby('assessment_dim')[feature].std()
        for dim in df['assessment_dim'].unique():
            if dim in mean_scores.index:
                print(f"  {dim.capitalize()} Average Score in {feature}: {mean_scores[dim]:.2f} ± {std_scores[dim]:.2f}")

def interpret_kappa(kappa, dimension_name):
    """
    解释 Kappa 值的意义
    """
    if kappa > 0.81:
        level = 'Almost Perfect'  # "极好的一致性 (Excellent)"
    elif kappa > 0.61:
        level = 'Substantial'  # "良好的一致性 (Good)"
    elif kappa > 0.41:
        level = 'Moderate'  # "中等一致性 (Moderate)"
    elif kappa > 0.21:
        level = 'Fair'  #"一般一致性 (Fair)"
    else:
        level = 'Slight'  # "较差的一致性 (Slight)"
    print(f"   -> Result for {dimension_name}: {level}")


